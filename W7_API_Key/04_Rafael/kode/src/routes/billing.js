const express = require('express');
const c = require('../controllers/billing');
const verifyJWT = require('../middlewares/verifyJWT');
const checkRoles = require('../middlewares/checkRoles');
const asyncHandler = require('../utils/asyncHandler');
const methodNotAllowed = require('../middlewares/methodNotAllowed');
const plansRouter = express.Router();
const subscriptionRouter = express.Router();
const paymentRouter = express.Router();
plansRouter.route('/').get(c.plans).all(methodNotAllowed('GET'));
subscriptionRouter.use(verifyJWT);
subscriptionRouter.route('/checkout').post(asyncHandler(c.checkout)).all(methodNotAllowed('POST'));
subscriptionRouter.route('/me').get(asyncHandler(c.me)).all(methodNotAllowed('GET'));
paymentRouter.use(verifyJWT);
paymentRouter.route('/').get(asyncHandler(c.myPayments)).all(methodNotAllowed('GET'));
paymentRouter.route('/admin/pending').get(checkRoles('admin'), asyncHandler(c.pendingPayments)).all(methodNotAllowed('GET'));
paymentRouter.route('/:id').get(asyncHandler(c.payment)).all(methodNotAllowed('GET'));
paymentRouter.route('/:id/confirm').patch(checkRoles('admin'), asyncHandler(c.confirm)).all(methodNotAllowed('PATCH'));
paymentRouter.route('/:id/cancel').patch(asyncHandler(c.cancel)).all(methodNotAllowed('PATCH'));
module.exports = { plansRouter, subscriptionRouter, paymentRouter };
